public class Relational {
    static void main() {
//        Relational operators
        int currentStreak = 20;
        int pastStreak = 10;

        System.out.println(currentStreak == pastStreak);
        System.out.println(currentStreak != pastStreak);
        System.out.println(currentStreak > pastStreak);
        System.out.println(currentStreak < pastStreak);
        System.out.println(currentStreak >= pastStreak);
        System.out.println(currentStreak <= pastStreak);
    }
}
