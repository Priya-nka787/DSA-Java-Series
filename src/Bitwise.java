public class Bitwise {
    static void main() {
//        Bitwise operators
        int x = 6;
        int y = 4;

        System.out.println(x&y);
        System.out.println(x|y);
        System.out.println(x^y);
        System.out.println(~x);
        System.out.println(x<<1);
        System.out.println(x>>y);
    }
}
